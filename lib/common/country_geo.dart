/// Web-mercator-free equirectangular projection: plain linear lat/lon to
/// unit-square, which is all a stylised backdrop needs (no navigation
/// accuracy requirement) and keeps this dependency-free.
Offset projectLatLon(Offset latLon, Size canvasSize) {
  final x = (latLon.dy + 180) / 360 * canvasSize.width;
  final y = (90 - latLon.dx) / 180 * canvasSize.height;
  return Offset(x, y);
}
